"""Installed capacity for the site's capacity factors: facilities/plant_capacity.csv -> site/src/lib/tracker/capacity.json.

facilities/plant_capacity.csv lists every plant the tracker shows with its installed MW and the dates it applies
(start and end inclusive, blank = open), so capacity can step with upgrades, derating, staged commissioning and
closures. Each row says where its figure comes from (basis: register = the EA plant register; override = researched
or read from a step in the metered output; pending = not generating yet, left out until it has a start date; source
and note give the detail). The evidence is
analysis/capacity_check.py and the "Installed capacity" section of analysis/README.md.

Capacity counts only from the first month the history has a plant's output, so a data gap doesn't pull a capacity
factor down: the embedded stations before Apr 1999, Kawerau Mill before 2020 ...

capacity.json, imported by the site (the Generation tab's mix table):
  steps   {island: {fuel: [[t, MW], ...]}}  the fuel's total installed MW from time t (ms, NZ local midnight) on
  roof    {"months": [...], island: [MW, ...]}  embedded solar capacity by month (the distributed generation registry
          less dispatched farms: facilities/rooftop_capacity.json; the live job's own table moves on from there)
  plants  [{name, fuel, isl, rows: [[start, end, MW], ...]}]  per plant, for plant pages

Not part of the history's rebuild fingerprint: editing the CSV changes no history month.

  python3 ingest/capacity.py           write capacity.json
  python3 ingest/capacity.py --check   fail if a plant the tracker shows has no capacity, a row is malformed, or
                                       capacity.json is out of date (run in .github/workflows/checks.yml)
"""
import csv
import json
import os
import sys
from datetime import date, datetime, timedelta

from common import FACILITIES, NZ, overrides

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
CSV = os.path.join(FACILITIES, 'plant_capacity.csv')
OUT = os.path.join(ROOT, 'site', 'src', 'lib', 'tracker', 'capacity.json')
FUELS = {'geo', 'bio', 'waste', 'coal', 'gas', 'diesel', 'hydro', 'wind', 'solar', 'batt'}
DISPATCH_FROM = date(2020, 9, 10)   # the daily dispatch files start: plants retired before then appear only in metered data


def rows():
    with open(CSV, newline='', encoding='utf-8') as f:
        return list(csv.DictReader(f))


def midnight(d):
    """ms at NZ local midnight starting date d."""
    return int(datetime(d.year, d.month, d.day, tzinfo=NZ).timestamp() * 1000)


def parse(s):
    return date.fromisoformat(s) if s else None


def build():
    R = [r for r in rows() if r['basis'] != 'pending']
    steps, plants = {}, {}
    for r in R:
        mw, a, b = float(r['mw']), parse(r['start']), parse(r['end'])
        ev = steps.setdefault(r['island'], {}).setdefault(r['fuel'], {})
        ta = midnight(a) if a else 0
        ev[ta] = ev.get(ta, 0) + mw
        if b:
            tb = midnight(b + timedelta(days=1))
            ev[tb] = ev.get(tb, 0) - mw
        p = plants.setdefault(r['plant'], {'name': r['plant'], 'fuel': r['fuel'], 'isl': r['island'], 'rows': []})
        p['rows'].append([r['start'] or None, r['end'] or None, mw])
    out_steps = {}
    for isl, by_fuel in sorted(steps.items()):
        out_steps[isl] = {}
        for fuel, ev in sorted(by_fuel.items()):
            run, seq = 0.0, []
            for t in sorted(ev):
                run += ev[t]
                v = round(max(0.0, run), 1)
                if seq and seq[-1][1] == v:
                    continue
                if seq and seq[-1][0] == t:
                    seq[-1][1] = v
                else:
                    seq.append([t, v])
            out_steps[isl][fuel] = seq
    with open(os.path.join(FACILITIES, 'rooftop_capacity.json')) as f:
        rc = json.load(f)
    roof = {'months': rc['months']}
    for isl in ('NI', 'SI'):
        tot = [0.0] * len(rc['months'])
        for cls in ('small', 'large', 'ground'):
            for pt, v in rc.get(cls, {}).items():
                if pt.startswith(isl):
                    tot = [x + y for x, y in zip(tot, v)]
        roof[isl] = [round(x, 1) for x in tot]
    for p in plants.values():
        p['rows'].sort(key=lambda x: x[0] or '')
    return {
        'about': 'Generated by ingest/capacity.py from facilities/plant_capacity.csv and facilities/rooftop_capacity.json. Do not edit.',
        'steps': out_steps, 'roof': roof, 'plants': sorted(plants.values(), key=lambda p: p['name']),
    }


def text(obj):
    return json.dumps(obj, ensure_ascii=False, separators=(',', ':')) + '\n'


def shown_plants():
    """Every plant name the tracker can show: the metered history's plants, and the dispatch data's plants (register
    and overrides) that were still running when the dispatch files start."""
    import pandas as pd
    from build_tracker import register, plant_groups
    names = set()
    with open(os.path.join(FACILITIES, 'metered_plants.csv'), newline='', encoding='utf-8') as f:
        names |= {r['plant'] for r in csv.DictReader(f) if r['plant'] not in ('', '-')}
    fuel, unit_names, _ = register()
    groups = plant_groups()
    reg = pd.read_csv(os.path.join(FACILITIES, 'plant_register.csv'))
    reg = reg.sort_values('EffectiveEndDate').drop_duplicates(['PointOfConnectionCode', 'UnitCode'], keep='last')
    retired = {}
    for r in reg.itertuples():
        d = pd.to_datetime(r.DateDecommissioned, dayfirst=True, errors='coerce')
        retired[(r.PointOfConnectionCode, r.UnitCode)] = None if pd.isna(d) else d.date()
    for k, n in unit_names.items():
        if k not in fuel:
            continue
        d = retired.get(k)
        if d is not None and d < DISPATCH_FROM:
            continue
        names.add(groups.get(n, n))
    for k, v in overrides().get('units', {}).items():
        names.add(groups.get(v['plant'], v['plant']))
    return names


def check():
    problems = []
    R = rows()
    have = {}
    for i, r in enumerate(R, start=2):
        where = f'plant_capacity.csv line {i} ({r["plant"]})'
        try:
            mw, a, b = float(r['mw']), parse(r['start']), parse(r['end'])
        except ValueError as e:
            problems.append(f'{where}: {e}')
            continue
        if mw <= 0:
            problems.append(f'{where}: MW must be positive')
        if r['fuel'] not in FUELS:
            problems.append(f'{where}: unknown fuel {r["fuel"]!r}')
        if r['island'] not in ('NI', 'SI'):
            problems.append(f'{where}: island must be NI or SI')
        if a and b and b < a:
            problems.append(f'{where}: ends before it starts')
        if r['basis'] not in ('register', 'override', 'pending'):
            problems.append(f'{where}: basis must be register, override or pending')
        if r['basis'] == 'pending' and (a or b):
            problems.append(f'{where}: a pending plant has no dates yet (give it a start and basis override once it generates)')
        have.setdefault(r['plant'], []).append((a or date.min, b or date.max))
    for p, spans in have.items():
        spans.sort()
        for (a1, b1), (a2, b2) in zip(spans, spans[1:]):
            if a2 <= b1:
                problems.append(f'{p}: capacity rows overlap ({a2} starts before {b1} ends)')
    for p in sorted(shown_plants() - set(have)):
        problems.append(f'{p}: shown by the tracker but has no row in facilities/plant_capacity.csv')
    want = text(build())
    try:
        with open(OUT, encoding='utf-8') as f:
            cur = f.read()
    except FileNotFoundError:
        cur = ''
    if cur != want:
        problems.append('site/src/lib/tracker/capacity.json is out of date: run python3 ingest/capacity.py and commit it')
    for m in problems:
        print('ERROR', m)
    return not problems


if __name__ == '__main__':
    if '--check' in sys.argv:
        ok = check()
        print('capacity: ok' if ok else 'capacity: problems found')
        sys.exit(0 if ok else 1)
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(text(build()))
    print('wrote', os.path.relpath(OUT, ROOT))
