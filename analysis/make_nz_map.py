"""Make site/src/lib/home/nzmap.js: simplified outlines of the North and South Islands (plus Stewart Island) as SVG
paths, from the EA's network zone shapes (EMI NetworkRegionShapefiles, WGS84 GeoJSON, CC BY 4.0), projected to
NZTM. Development only (needs shapely and pyproj).

  python3 analysis/make_nz_map.py <WGS84_GeoJSON_Zone.JSON>
"""
import json, os, sys
from pyproj import Transformer
from shapely.geometry import shape, MultiPolygon, Polygon
from shapely.ops import unary_union, transform

W = 420                       # viewBox width; height follows the shape
TOL_M = 2500                  # simplification tolerance (metres)
MIN_KM2 = 600                 # drop smaller islands, except Stewart Island
d = json.load(open(sys.argv[1]))
geo = {f['properties']['ID']: shape(f['geometry']) for f in d['features']}
tr = Transformer.from_crs(4326, 2193, always_xy=True)
proj = lambda g: transform(lambda x, y, z=None: tr.transform(x, y), g)
groups = {'ni': ['UNI', 'CNI', 'LNI'], 'si': ['USI', 'LSI', 'STI']}
shapes = {}
for k, ids in groups.items():
    g = proj(unary_union([geo[i] for i in ids if i in geo]).buffer(0))
    polys = list(g.geoms) if isinstance(g, MultiPolygon) else [g]
    keep = [p for p in polys if p.area / 1e6 >= MIN_KM2 or (k == 'si' and p.centroid.y < 4.83e6 and p.area / 1e6 > 1000)]
    shapes[k] = MultiPolygon([Polygon(p.exterior) for p in keep]).simplify(TOL_M)
allb = unary_union(list(shapes.values())).bounds
x0, y0, x1, y1 = allb
s = W / (x1 - x0)
H = round((y1 - y0) * s)
pt = lambda x, y: (round((x - x0) * s, 1), round((y1 - y) * s, 1))
def path(g):
    out = []
    for p in (g.geoms if hasattr(g, 'geoms') else [g]):
        c = [pt(x, y) for x, y in p.exterior.coords]
        out.append('M' + 'L'.join(f'{a},{b}' for a, b in c[:-1]) + 'Z')
    return ''.join(out)
points = {'ben': (170.20, -44.57), 'hay': (174.98, -41.15), 'akl': (174.76, -36.85), 'wlg': (174.78, -41.29), 'chc': (172.63, -43.53)}
P = {k: pt(*tr.transform(lon, lat)) for k, (lon, lat) in points.items()}
js = ('// Generated by analysis/make_nz_map.py from the Electricity Authority\'s network zone shapes (EMI, CC BY 4.0),\n'
      '// projected to NZTM and simplified. Coordinates are in the viewBox.\n'
      f'export const VIEW = {{ w: {W}, h: {H} }};\n'
      f'export const NI = "{path(shapes["ni"])}";\n'
      f'export const SI = "{path(shapes["si"])}";\n'
      f'export const PTS = {json.dumps({k: list(v) for k, v in P.items()})};\n')
out = os.path.join(os.path.dirname(__file__), '..', 'site', 'src', 'lib', 'home', 'nzmap.js')
open(out, 'w').write(js)
print(f'viewBox {W}x{H}, {len(js)/1024:.1f} KB, points {P}')
