import { chromium } from 'playwright';
const [,, out, w = 1280, h = 800, dpr = 1, phone = ''] = process.argv;
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: +w, height: +h }, deviceScaleFactor: +dpr, isMobile: !!phone, hasTouch: !!phone });
const p = await ctx.newPage();
await p.route('**/data/tracker.json', r => r.fulfill({ path: '/tmp/tracker.json', contentType: 'application/json' }));
await p.route('**/data/beat', r => r.fulfill({ status: 204 }));
await p.goto('http://localhost:4173/landscape?cards=0');
await p.waitForFunction(() => !/Loading/.test(document.querySelector('#when')?.textContent ?? 'Loading'), null, { timeout: 60000 });
await p.getByRole('button', { name: 'Play with dials' }).click();
await p.waitForTimeout(1500);
await p.screenshot({ path: out });
await b.close();
